/**
 * Генерирует текст релиза: что внутри, как установить, что изменилось.
 * Запускается в CI: node scripts/release-notes.mjs 1.0.0 > RELEASE_NOTES.md
 */
import { readFileSync } from 'node:fs';

const version = (process.argv[2] ?? JSON.parse(readFileSync('package.json', 'utf8')).version).replace(/^v/i, '');
const singbox = process.env.SINGBOX_VERSION ?? '1.14.4';
const hev = process.env.HEV_VERSION ?? '3.0.1';
const repo = process.env.GITHUB_REPOSITORY ?? 'kayorissss/SHUZU';

const notes = `## SHUZU ${version}

VPN-клиент для Windows и Android. Ядро **sing-box ${singbox}** уже внутри приложения —
ничего докачивать не нужно.

### Что скачать

| Платформа | Файл | Как ставить |
|---|---|---|
| Windows 10/11 x64 | \`SHUZU-Setup-${version}-x64.exe\` | Запустить, установить, открыть |
| Android 7.0+ | \`SHUZU-${version}-android.apk\` | Открыть файл, разрешить установку из этого источника |

Контрольные суммы — в файлах \`SHA256SUMS-windows.txt\` и \`SHA256SUMS-android.txt\`.

### Как подключиться

1. При первом запуске нажмите **«+ Из буфера обмена»** (ссылка-подписка уже скопирована) или **«QR-код»**.
2. Дождитесь списка серверов и пингов.
3. Нажмите большую круглую кнопку — приложение само выберет самый быстрый сервер.
4. Если не подключается — откройте **Ещё → Диагностика**: она по пунктам объяснит, что мешает,
   и предложит исправление. Проверка блокировок покажет, фильтрует ли провайдер трафик.

### Внутри

- Ядро sing-box ${singbox} (VLESS/Reality, VMess, Trojan, Shadowsocks, Hysteria2, TUIC), tun2socks hev ${hev} на Android.
- TUN-режим (весь трафик) и режим системного прокси на Windows; VpnService на Android.
- Белые списки: банки, госуслуги, маркетплейсы и другие российские сервисы идут напрямую.
- Авто-выбор сервера по пингу и потерям, избранное, несколько подписок, обновление по расписанию.
- Диагностика сети и проверка блокировок/замедления провайдером.
- Проверка обновлений прямо в приложении.

### Замечания по безопасности

- Windows: для TUN-режима нужны права администратора (создание виртуального адаптера).
  Без прав приложение работает в режиме системного прокси.
- Подпись кода не настроена, поэтому SmartScreen может показать предупреждение
  «Неизвестный издатель» — это ожидаемо для сборки из открытого репозитория.
- APK, собранный без секретов подписи, подписан debug-ключом: обновление поверх
  установленной версии с другим ключом потребует удаления приложения.

Исходный код и issues: https://github.com/${repo}
`;

process.stdout.write(notes);
