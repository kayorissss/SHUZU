/**
 * Сборка и трактовка отчёта диагностики.
 *
 * Здесь же — «человеческие» объяснения: почему VPN может не работать на этом
 * компьютере, даже если на телефоне всё подключается.
 */
import type { DiagCheck, DiagReport } from './types';

export function buildReport(checks: DiagCheck[], now = Date.now()): DiagReport {
  const scored = checks.filter((c) => (c.weight ?? 0) > 0);
  const total = scored.reduce((a, c) => a + (c.weight ?? 0), 0) || 1;
  let earned = 0;
  for (const c of scored) {
    const w = c.weight ?? 0;
    if (c.status === 'ok') earned += w;
    else if (c.status === 'warn') earned += w * 0.45;
    else if (c.status === 'info') earned += w;
  }
  const score = Math.round((earned / total) * 100);
  const fails = checks.filter((c) => c.status === 'fail');
  const warns = checks.filter((c) => c.status === 'warn');

  const verdict: DiagReport['verdict'] = fails.length ? 'blocked' : warns.length ? 'degraded' : 'healthy';

  return {
    createdAt: now,
    score,
    checks,
    verdict,
    summary: summarize(verdict, fails, warns, score),
  };
}

function summarize(verdict: DiagReport['verdict'], fails: DiagCheck[], warns: DiagCheck[], score: number): string {
  if (verdict === 'healthy' && !warns.length) {
    return 'Всё в порядке: ядро на месте, сеть доступна, системные настройки не мешают. Если VPN всё равно не подключается — проблема на стороне сервера или подписки.';
  }
  if (verdict === 'healthy') {
    return `Работает, но есть замечания (${warns.length}). На подключение не влияют, но лучше исправить: ${warns[0]?.title.toLowerCase() ?? ''}.`;
  }
  if (verdict === 'degraded') {
    return `Найдено ${warns.length} предупреждени${warns.length === 1 ? 'е' : 'я'}. Подключение возможно, но может быть нестабильным или медленным.`;
  }
  const main = fails[0];
  return `Критично (${score}/100): ${main ? main.title.toLowerCase() : 'есть блокирующая проблема'}${fails.length > 1 ? ` и ещё ${fails.length - 1}` : ''}. Ниже — что именно сделать.`;
}

